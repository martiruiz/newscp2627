#!/usr/bin/env node
// Writes admin/js/smart-taxonomy.js (categories + allowed values) from taxonomy.mjs, for the admin review screen.
//   cd pipeline && node library/export-taxonomy.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { CATEGORIES, AI_VALUES } from "./taxonomy.mjs";
const out = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "..", "admin", "js", "smart-taxonomy.js");
fs.writeFileSync(out, `// Generated by pipeline/library/export-taxonomy.mjs from taxonomy.mjs — don't edit by hand.\nwindow.SCP_SMART = ${JSON.stringify({ categories: CATEGORIES, values: AI_VALUES }, null, 2)};\n`);
console.log(`Wrote ${out}`);
